"""P0 pipeline trace: which stories become visible at which simulated minute, and why.

    python -m byline.tools.story_timeline            # all scenarios -> docs/story-timeline.md

For every candidate: source evidence window, detector output, whether a REAL recorded Foundry run
exists (with trace ids and verifier verdict), what a cache-only session delivers, and when/why it is
retracted. Runs a real ReplaySession + InsightService in cache-only mode (no model client is created).
"""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any

from byline.api.sessions import ReplaySession
from byline.config import REPO_ROOT, Settings
from byline.storage.fixtures import available_scenarios, load_package
from byline.stories.service import RECORDED_DIR, InsightService
from byline.world.clock import broadcast_clock


def clock_at(pkg: Any, ms: int) -> str:
    starts = [(e.period, e.elapsed_ms) for e in pkg.events if e.type == "period.started"]
    period, start = starts[0]
    for p, s in starts:
        if ms >= s:
            period, start = p, s
    return broadcast_clock(period, ms - start)


def recorded_index() -> dict[str, dict[str, Any]]:
    out: dict[str, dict[str, Any]] = {}
    for path in RECORDED_DIR.glob("*.json"):
        d = json.loads(path.read_text(encoding="utf-8"))
        out[d["insight"]["candidate_id"]] = {"file": path.name, **d}
    return out


def trace(scenario: str) -> list[dict[str, Any]]:
    pkg = load_package(scenario)
    svc = InsightService(Settings(byline_ai_provider="foundry", byline_ai_cache_only=True,
                                  foundry_deployment="gpt-4.1-mini"), lambda: [], lambda: None,
                         cache_dir=Path("_unused_cache_dir"))
    s = ReplaySession("timeline", pkg, on_candidate=svc.submit, on_retract=svc.retract)
    q = s.subscribe()
    s.playing, s.speed = True, 60
    step_s = 0.05  # 3 s of match per tick: delivery must happen in the tick that releases the detection event
    first_seen: dict[str, dict[str, Any]] = {}
    retracted_at: dict[str, int] = {}
    while s.cursor < len(pkg.events):
        s.tick(step_s)
        while not q.empty():
            m = q.get_nowait()
            if m.event == "insight_update":
                cid = m.data["candidate_id"]
                first_seen.setdefault(cid, {"playhead_ms": s.playhead_ms, "stage": m.data["stage"],
                                            "checker": (m.data["insight"] or {}).get("verification", {})
                                            .get("checker_name")})
                if m.data["stage"] == "retracted":
                    retracted_at.setdefault(cid, s.playhead_ms)
    rec = recorded_index()
    rows = []
    for c in s.intelligence.candidates:
        r = rec.get(c.candidate_id)
        seen = first_seen.get(c.candidate_id, {})
        trace_ = (r or {}).get("trace") or {}
        rows.append({
            "scenario": scenario, "candidate_id": c.candidate_id, "pattern": c.pattern_type, "team": c.team_id,
            "window": f"{clock_at(pkg, c.window_start_ms)}–{clock_at(pkg, c.window_end_ms)}",
            "detected": f"{c.display_clock} ({clock_at(pkg, c.detected_at_ms)})",
            "detected_ms": c.detected_at_ms, "evidence_events": len(c.evidence_event_ids),
            "delivered_at": clock_at(pkg, seen["playhead_ms"]) if seen else "never",
            "delivered_lag_ms": seen["playhead_ms"] - c.detected_at_ms if seen else None,
            "delivered_stage": seen.get("stage"), "checker": seen.get("checker"),
            "real_run": bool(r), "real_calls": trace_.get("total_model_calls"),
            "real_response_ids": sum(len(st.get("response_ids", [])) for st in trace_.get("steps", [])),
            "verifier": next((st["output"]["verdict"] for st in trace_.get("steps", [])
                              if st["agent"] == "verifier" and st.get("output")), None),
            "spanish": bool([k for k in ((r or {}).get("insight", {}).get("audience_variants", {})
                                         .get("translations", {})) if k.startswith("es.")]),
            "retracted_at": clock_at(pkg, retracted_at[c.candidate_id]) if c.candidate_id in retracted_at else "",
        })
    return rows


def markdown(rows: list[dict[str, Any]]) -> str:
    lines = ["# Story Radar timeline (P0 trace)", "",
             "Generated by `python -m byline.tools.story_timeline` from a real ReplaySession + InsightService in "
             "cache-only mode (no model calls). `real_run` = a recorded REAL Foundry run exists for this candidate "
             "(served as a flagged cache hit); otherwise the card is a labelled detector summary.", ""]
    for scen in sorted({r["scenario"] for r in rows}):
        lines += [f"## {scen}", "",
                  "| Detected (clock) | Story | Team | Evidence window | Events | Delivered at | Card state | Real Foundry run | Verifier | ES | Retracted |",
                  "|---|---|---|---|---|---|---|---|---|---|---|"]
        for r in [x for x in rows if x["scenario"] == scen]:
            real = f"yes ({r['real_calls']} calls, {r['real_response_ids']} response ids)" if r["real_run"] else "no"
            lines.append(f"| {r['detected']} | {r['pattern']} `{r['candidate_id']}` | {r['team']} | {r['window']} | "
                         f"{r['evidence_events']} | {r['delivered_at']} | {r['delivered_stage']} "
                         f"({(r['checker'] or '').replace('verifier_agent+deterministic_validator', 'AI verified')}) | "
                         f"{real} | {r['verifier'] or '–'} | {'yes' if r['spanish'] else '–'} | "
                         f"{r['retracted_at'] or '–'} |")
        lines.append("")
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    scenarios = argv or available_scenarios()
    rows = [r for s in scenarios for r in trace(s)]
    out = REPO_ROOT / "docs" / "story-timeline.md"
    out.write_text(markdown(rows), encoding="utf-8")
    print(markdown(rows))
    late = [r for r in rows if r["delivered_lag_ms"] is None or r["delivered_lag_ms"] > 3000]
    print(f"\n{len(rows)} candidates; not delivered in the tick that released the detection event: {len(late)}")
    return 1 if late else 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
