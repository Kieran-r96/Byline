// V3 signature flow: live feed -> tactical moment -> the moment / what happened / what if? (real app).
//   node scripts/v3-shots.mjs <out-dir> [--url http://localhost:4173] [--width 1440 --height 900] [--role Commentator|Fan] [--fan Discover]
import { mkdirSync } from 'node:fs'
import { chromium } from '@playwright/test'

const arg = (k, d) => (process.argv.includes(k) ? process.argv[process.argv.indexOf(k) + 1] : d)
const out = process.argv[2] ?? '../../docs/screenshots/v3'
const url = arg('--url', 'http://localhost:4173')
const width = Number(arg('--width', 1440))
const height = Number(arg('--height', 900))
const roleName = arg('--role', 'Commentator')
const fan = arg('--fan', null)
const prefix = arg('--prefix', `${roleName.toLowerCase()}${fan ? '-' + fan.toLowerCase() : ''}-${width}`)
mkdirSync(out, { recursive: true })
const browser = await chromium.launch()
const page = await browser.newPage({ viewport: { width, height }, deviceScaleFactor: 1 })
page.on('pageerror', (e) => console.log('pageerror', e.message))
await page.goto(url)
await page.locator('.mt[data-loading="false"]').waitFor()
const radio = page.getByRole('radio', { name: roleName, exact: true }).first()
if (!(await radio.isVisible())) await page.getByRole('button', { name: /^View/ }).first().click()
await page.getByRole('radio', { name: roleName, exact: true }).first().click()
if (fan) await page.getByRole('radio', { name: fan, exact: true }).first().click()
await page.keyboard.press('Escape')
await page.getByRole('slider', { name: 'Replay position' }).fill('500')
await page.waitForTimeout(2200)
await page.screenshot({ path: `${out}/${prefix}-feed.png` })
console.log('wrote feed')
const card = page.locator('.sig').filter({ hasText: /was open as/i }).first()
await card.getByRole('button', { name: 'Show why' }).click()
await page.locator('.tactic__title').waitFor()
await page.waitForTimeout(1400)
await page.screenshot({ path: `${out}/${prefix}-step1-moment.png` })
await page.waitForTimeout(2600)
await page.screenshot({ path: `${out}/${prefix}-step2-happened.png` })
await page.waitForTimeout(3600)
await page.screenshot({ path: `${out}/${prefix}-step3-whatif.png` })
console.log('wrote steps')
await browser.close()
