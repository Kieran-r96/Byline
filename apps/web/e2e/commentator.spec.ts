test('a new user opens a player, finds a fact, marks it used and is back on the match within seconds', async ({ page }) => {
  await loadApp(page)
  await scrubTo(page, 1700)
  await page.getByRole('button', { name: 'Play replay' }).click()
  await expect(page.getByRole('button', { name: 'Pause replay' })).toBeVisible()
  const started = Date.now()
  const before = await position(page)
  await page.locator('.sp__player').filter({ hasText: 'Ferrandi' }).first().click()
  const file = page.getByRole('dialog', { name: 'Player file' })
  const fact = file.locator('.hero-fact')
  await expect(fact).toBeVisible()
  await expect(fact).toBeInViewport()
  await fact.getByRole('button', { name: 'Mark used' }).click()
  await expect(page.getByRole('status').filter({ hasText: 'Marked as used' })).toBeVisible()
  await page.getByRole('button', { name: 'Close and return to the match' }).click()
  await expect(file).toBeHidden()
  const seconds = (Date.now() - started) / 1000
  expect(seconds).toBeLessThan(8)
  // the match never stopped: the replay kept playing while the file was open
  await expect.poll(() => position(page)).toBeGreaterThan(before)
  await expect(page.getByRole('button', { name: 'Pause replay' })).toBeVisible()
})

