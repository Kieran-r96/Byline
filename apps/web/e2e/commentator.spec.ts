test('signature: the 7th-minute moment opens a guided explanation; Back to match restores the exact position', async ({ page }) => {
  await loadApp(page)
  await scrubTo(page, 390)
  const moment = page.locator('.moment').filter({ hasText: /was open as/i })
  await expect(moment).toBeVisible()
  await expect(moment.locator('.verified-line')).toContainText('Verified by Foundry agents')
  const before = await position(page)
  await moment.getByRole('button', { name: 'Show the play' }).click()
  const dialog = page.getByRole('dialog', { name: 'Tactical analysis' })
  await expect(dialog).toContainText(/Haddad-Rhys was open/)
  await expect(dialog.locator('.vread')).toContainText('Deep analysis · verified by Foundry agents')
  await expect(dialog).not.toContainText(/would have scored|chance of scoring|\d+%/)
  await dialog.getByRole('button', { name: /Back to match/ }).click()
  await expect(dialog).toHaveCount(0)
  expect(Math.abs((await position(page)) - before)).toBeLessThan(3)
  await expect(moment.getByRole('button', { name: 'Show the play' })).toBeFocused()
})

test('story evidence and its replay never lose the viewer: Back to match returns to where they were', async ({ page }) => {
  await loadApp(page)
  await scrubTo(page, 1700)
  const before = await position(page)
  await openHistory(page, 'Developing')
  const story = page.locator('.dev[data-kind="ai-story"]').filter({ hasText: /right channel/i }).first()
  await expect(story).toContainText('verified by Foundry agents')
  await story.getByRole('button', { name: 'See the evidence' }).click()
  await expect(page.getByText('Real Foundry run')).toBeVisible({ timeout: 10_000 })
  await expect.poll(() => page.locator('.evidence__events li').count()).toBeGreaterThanOrEqual(5)
  await page.getByRole('button', { name: 'Replay evidence' }).click()
  await expect.poll(() => position(page)).toBeLessThan(1600)
  await page.getByRole('button', { name: 'Back to match' }).click()
  await expect(page.locator('.evidence')).toHaveCount(0)
  await expect.poll(async () => Math.abs((await position(page)) - before)).toBeLessThan(3)
})

