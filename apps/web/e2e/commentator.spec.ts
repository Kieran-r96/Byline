test('a shirt opens the player file: one big fact with Mark used and Pin, big numbers, contextual actions', async ({ page }) => {
  await loadApp(page)
  await scrubTo(page, 1800)
  await page.locator('.sp__player').filter({ hasText: 'Vantreight' }).first().click()
  const file = page.getByRole('dialog', { name: 'Player file' })
  await expect(file.locator('.sf__name')).toContainText('Vantreight')
  // the most relevant fact is the hero, in large type
  const hero = file.locator('.hero-fact')
  await expect(hero).toContainText('100th')
  await expect(file.locator('.bigs')).toContainText('Passes found')
  // match impact is open first: the goal he scored, from the official events
  await expect(file.getByRole('button', { name: 'Match impact' })).toHaveAttribute('aria-pressed', 'true')
  await expect(file.locator('.sf__inv')).toContainText('28')
  for (const action of ['This season', 'Career', 'Milestones', 'Against Riverton', 'Tactical involvement']) {
    await file.getByRole('button', { name: action }).click()
    await expect(file.locator('.sf__panel .dz__sec').first()).toBeVisible()
  }
  const heroText = (await hero.locator('.hero-fact__text').innerText()).trim()
  await hero.getByRole('button', { name: 'Mark used' }).click()
  await expect(page.getByRole('status').filter({ hasText: 'Marked as used' })).toBeVisible()
  await expect(hero.locator('.hero-fact__text')).not.toHaveText(heroText)
  await file.getByRole('button', { name: /^All facts/ }).click()
  const facts = file.locator('.fact')
  await expect(facts.first()).toBeVisible()
  const first = (await facts.first().locator('.fact__text').innerText()).trim()
  await facts.first().getByRole('button', { name: 'Pin to top' }).click()
  await expect(facts.first().getByRole('button', { name: 'Pinned' })).toBeVisible()
  await facts.first().getByRole('button', { name: 'Mark used' }).click()
  await expect(page.getByRole('status').filter({ hasText: 'Marked as used' })).toBeVisible()
  await expect(file.locator('.fact .fact__text', { hasText: first })).toHaveCount(0)
  // the moment stays in view beside the file (non-modal), and the file closes back to the match
  await expect(page.locator('.moment')).toBeVisible()
  await page.getByRole('button', { name: 'Close and return to the match' }).click()
  await expect(file).toBeHidden()
})

